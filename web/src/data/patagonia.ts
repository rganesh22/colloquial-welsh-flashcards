import type { Dialect, VocabCard } from '../lib/types'

/**
 * Y Wladfa phrase book: spoken chunks for the Patagonia trip plan, in the
 * order the plan introduces them. Production forms are clear colloquial
 * learner Welsh (what Patagonian learners are taught); heritage forms that
 * older Wladfa speakers use are taught for recognition, mostly in p13.
 *
 * Dialect notes for p13 follow Iwan Wyn Rees, Gwerddon 36 (2024), and the
 * BBC Cymru Fyw / British Council reports on Cymraeg y Wladfa.
 */

type RawCard = Omit<VocabCard, 'bookId' | 'number' | 'sense'>

/**
 * [welsh, english, note?, dialect?, idSlug?]
 * Ids come from the Welsh text. When a card's Welsh is corrected, idSlug keeps
 * the original slug so learners don't lose their progress on it.
 */
type Row = [string, string, string?, Dialect?, string?]

function slug(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[’'…?!.,"“”()/]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40)
}

function lesson(lessonId: string, tag: string, rows: Row[]): RawCard[] {
  const seen = new Set<string>()
  return rows.map(([welsh, english, notes, dialect, idSlug]) => {
    let id = `yw-${lessonId}-${idSlug ?? slug(welsh)}`
    while (seen.has(id)) id += '-2'
    seen.add(id)
    return {
      id,
      lessonId,
      welsh,
      english,
      pos: 'phrase',
      ...(notes ? { notes } : {}),
      ...(dialect ? { dialect } : {}),
      tags: ['patagonia', tag],
    }
  })
}

