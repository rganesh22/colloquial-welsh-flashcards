import daysJson from '../data/sprint/days.json'
import videosJson from '../data/sprint/videos.json'
import wordsJson from '../data/sprint/words.json'
import { cardsForLesson } from '../data/deck'
import { isVocabUnseen, knownFromOtherDeck, localCalendarDay } from './srs'
import { daysBetween, type SprintBlock, type SprintState } from './trip'
import type { DirectionMode, ProgressMap } from './types'

/**
 * The 50-day sprint: 25 words a day (taught in example sentences built only
 * from words you already know), one speaking pattern, an episode of a story
 * and the Easy Welsh videos you can now follow. Content is generated by
 * scripts/sprint/*.mjs.
 */

export const SPRINT_DAYS = 50
export const SPRINT_NEW_PER_DAY = 25
/** The most reviews a day the learner can manage. */
export const SPRINT_REVIEW_CAP = 250

export interface SprintWord {
  id: string
  day: number
  n: number
  cy: string
  en: string
  pos: string
  gender?: string
  note?: string
  patagonia?: boolean
  videos?: string[]
  ex?: { cy: string; en: string }
}

export interface CyEn {
  cy: string
  en: string
}

export interface SprintDay {
  day: number
  title: string
  why: string
  catchUp: boolean
  grammar: { explain: string; examples: CyEn[] }
  build: CyEn[]
  story: {
    title: string
    lines: CyEn[]
    questions: { q: string; en: string; options: string[]; answer: number }[]
  }
  speak: { prompt: string; cy: string; en: string }[]
}

export interface SprintVideo {
  id: string
  title: string
  series: string
  minutes: number
  words: number
  /** Share of the video's words you know by the end of each day (index 0 = day 1). */
  coverage: number[]
  readyDay: number | null
}

export const SPRINT_WORDS = wordsJson as SprintWord[]
export const SPRINT_DAY_CONTENT = daysJson as SprintDay[]
export const SPRINT_VIDEOS = videosJson as SprintVideo[]

export const isCatchUpDay = (day: number) => day % 7 === 0

export function sprintDay(day: number): SprintDay | undefined {
  return SPRINT_DAY_CONTENT.find((d) => d.day === day)
}

export const SPRINT_LESSON_ID = (day: number) => `d${day}`

// ---------- your progress ----------

export type { SprintBlock, SprintState } from './trip'
export const SPRINT_BLOCKS: SprintBlock[] = ['words', 'pattern', 'story', 'speak']

export function markBlock(s: SprintState, day: number, block: SprintBlock): SprintState {
  const have = s.done[day] ?? []
  if (have.includes(block)) return s
  return { ...s, done: { ...s.done, [day]: [...have, block] } }
}

/** Today's new sprint cards you haven't met yet, here or as the same word in another deck. */
export function unseenWordIds(progress: ProgressMap, day: number, direction: DirectionMode): string[] {
  return cardsForLesson('sprint', SPRINT_LESSON_ID(day))
    .filter((c) => isVocabUnseen(progress, c, direction) && !knownFromOtherDeck(progress, c, direction))
    .map((c) => c.id)
}

/** How many of the day's words you already knew from your other flashcards. */
export function knownFromFlashcards(progress: ProgressMap, day: number, direction: DirectionMode): number {
  return cardsForLesson('sprint', SPRINT_LESSON_ID(day)).filter(
    (c) => isVocabUnseen(progress, c, direction) && knownFromOtherDeck(progress, c, direction),
  ).length
}

export function blockDone(
  s: SprintState,
  day: number,
  block: SprintBlock,
  progress: ProgressMap,
  direction: DirectionMode,
): boolean {
  if (s.done[day]?.includes(block)) return true
  // The words are done once every one of the day's words has been met.
  if (block === 'words' && !isCatchUpDay(day)) {
    return cardsForLesson('sprint', SPRINT_LESSON_ID(day)).length > 0 && unseenWordIds(progress, day, direction).length === 0
  }
  return false
}

export function dayDone(s: SprintState, day: number, progress: ProgressMap, direction: DirectionMode): boolean {
  return SPRINT_BLOCKS.every((b) => blockDone(s, day, b, progress, direction))
}

/** The first day not finished: you move on when you finish, not when the calendar says. */
export function currentSprintDay(s: SprintState, progress: ProgressMap, direction: DirectionMode): number {
  for (let d = 1; d <= SPRINT_DAYS; d++) if (!dayDone(s, d, progress, direction)) return d
  return SPRINT_DAYS
}

/** Calendar days left until the deadline (0 on the day itself). */
export function daysToFinish(s: SprintState, today = localCalendarDay()): number {
  return daysBetween(today, s.finishBy)
}

/** Which day the calendar says you should be on, so that day 50 lands on the deadline. */
export function calendarDay(s: SprintState, today = localCalendarDay()): number {
  return Math.min(SPRINT_DAYS, Math.max(1, SPRINT_DAYS - daysToFinish(s, today)))
}

/** The Easy Welsh video to watch today: the newest one you can mostly follow, and the next one. */
export function videosFor(day: number): { now?: SprintVideo; next?: SprintVideo } {
  const known = (v: SprintVideo) => v.coverage[day - 1] ?? 0
  const ready = SPRINT_VIDEOS.filter((v) => v.readyDay != null && v.readyDay <= day)
  const now = ready.sort((a, b) => (b.readyDay ?? 0) - (a.readyDay ?? 0))[0]
  const next = SPRINT_VIDEOS.filter((v) => v !== now && (v.readyDay == null || v.readyDay > day)).sort(
    (a, b) => known(b) - known(a),
  )[0]
  return { now, next }
}

/** Words you'll know by the end of `day`. */
export function wordsByDay(day: number): number {
  return SPRINT_WORDS.filter((w) => w.day <= day).length
}

/** Sprint word ids you've learned (here, or as the same word in another deck). */
export function learnedSprintIds(progress: ProgressMap, direction: DirectionMode): Set<string> {
  const out = new Set<string>()
  for (let d = 1; d <= SPRINT_DAYS; d++) {
    for (const c of cardsForLesson('sprint', SPRINT_LESSON_ID(d))) {
      if (!isVocabUnseen(progress, c, direction) || knownFromOtherDeck(progress, c, direction)) out.add(c.id)
    }
  }
  return out
}

/** Videos you're ready for from this day. */
export function videosReadyOn(day: number): SprintVideo[] {
  return SPRINT_VIDEOS.filter((v) => v.readyDay === day)
}
